-- Pharmacy advice, patient choice and billing (reference implementation, synthetic data only)

CREATE TABLE advisories (
  advisory_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  rx_id             NUMBER NOT NULL REFERENCES prescriptions,
  drug_id           NUMBER NOT NULL REFERENCES drug_master,
  item_qty          NUMBER(6) DEFAULT 1,
  unit_price        NUMBER(10,2),                     -- price frozen when the suggestion is made, so later price changes never alter a bill
  suggested_by      VARCHAR2(12) CHECK (suggested_by IN ('PHARMACIST','DOCTOR')),
  note              VARCHAR2(400) NOT NULL,           -- visible to patient, doctor and pharmacy
  covered_flag      CHAR(1) NOT NULL CHECK (covered_flag IN ('Y','N')),  -- set by the system, never typed by staff
  patient_decision  VARCHAR2(10) CHECK (patient_decision IN ('ACCEPTED','DECLINED')),
  patient_note      VARCHAR2(400),
  created_at        DATE DEFAULT SYSDATE,
  decided_at        DATE
);

-- covered_flag is derived from the drug and the member's plan, not entered by hand
CREATE OR REPLACE TRIGGER trg_advisories_covered
BEFORE INSERT OR UPDATE OF drug_id ON advisories
FOR EACH ROW
DECLARE
  v_on_formulary drug_master.on_formulary%TYPE;
  v_form_req     insurance_plans.formulary_required%TYPE;
  v_price        drug_master.unit_cost%TYPE;
BEGIN
  SELECT dm.on_formulary, ip.formulary_required, dm.unit_cost
    INTO v_on_formulary, v_form_req, v_price
    FROM prescriptions rx
    JOIN members m           ON m.member_id = rx.member_id
    JOIN insurance_plans ip  ON ip.plan_id = m.plan_id
    JOIN drug_master dm      ON dm.drug_id = :NEW.drug_id
   WHERE rx.rx_id = :NEW.rx_id;
  IF :NEW.unit_price IS NULL OR UPDATING('DRUG_ID') THEN :NEW.unit_price := v_price; END IF;
  :NEW.covered_flag := CASE WHEN v_on_formulary = 'Y' OR v_form_req = 'N' THEN 'Y' ELSE 'N' END;
END;
/

-- Billing follows the patient's choices:
--   insurer pays the approved claim amount
--   patient pays any shortfall on the claim, plus accepted advice items that are not covered
CREATE OR REPLACE VIEW v_patient_bill AS
SELECT rx.member_id,
       rx.rx_id,
       NVL(SUM(c.approved_amount), 0)                                    AS insurer_pays,
       NVL(SUM(c.claimed_amount - NVL(c.approved_amount,0)), 0)          AS claim_shortfall,
       NVL((SELECT SUM(a.item_qty * a.unit_price)
              FROM advisories a
             WHERE a.rx_id = rx.rx_id AND a.patient_decision = 'ACCEPTED'
               AND a.covered_flag = 'N'), 0)                             AS accepted_uncovered_items
FROM prescriptions rx
JOIN dispense_records ds ON ds.rx_id = rx.rx_id
JOIN claims c            ON c.dispense_id = ds.dispense_id
GROUP BY rx.member_id, rx.rx_id;

-- Notification outbox: written in the same transaction as the business change.
-- A separate Python worker reads PENDING rows and sends email, SMS and a Redis push message.
-- Message text is generic ("An update is available"); details stay in the database and show after login.
CREATE TABLE notification_outbox (
  outbox_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  member_id     NUMBER NOT NULL REFERENCES members,
  event_type    VARCHAR2(20) CHECK (event_type IN ('CLAIM','DISPENSARY','ADVISORY','BILL')),
  ref_id        NUMBER,                       -- claim_id, rx_id or advisory_id the update is about
  created_at    DATE DEFAULT SYSDATE NOT NULL,
  status        VARCHAR2(10) DEFAULT 'PENDING' CHECK (status IN ('PENDING','SENT','PARTIAL','FAILED')),
  email_status  VARCHAR2(10) DEFAULT 'PENDING',
  sms_status    VARCHAR2(10) DEFAULT 'PENDING',
  push_status   VARCHAR2(10) DEFAULT 'PENDING',
  attempts      NUMBER(3) DEFAULT 0,          -- send counter; hard cap of 5 sends, then the front desk is alerted
  next_attempt  DATE,                         -- resend every 10 minutes until acknowledged or the cap is reached
  last_error    VARCHAR2(400),
  read_at       DATE,                         -- set when the patient logs in and opens the update (the acknowledgement)
  frontdesk_alerted_at DATE                   -- set when no acknowledgement came and the front desk was asked to call the patient
);

-- Per-patient channel consent, chosen at admission or insurance enrolment; opt-out by mutual consent
CREATE TABLE member_contact_prefs (
  member_id     NUMBER PRIMARY KEY REFERENCES members,
  email_address VARCHAR2(200),
  mobile_no     VARCHAR2(20),
  email_opt_in  CHAR(1) DEFAULT 'Y' CHECK (email_opt_in IN ('Y','N')),
  sms_opt_in    CHAR(1) DEFAULT 'Y' CHECK (sms_opt_in IN ('Y','N')),
  push_opt_in   CHAR(1) DEFAULT 'Y' CHECK (push_opt_in IN ('Y','N')),
  consent_at    DATE
);
CREATE INDEX ix_outbox_pending ON notification_outbox (status, created_at);
