-- Access control and audit (reference sketch; NOT run on Oracle, test in your APEX workspace first)
-- Delivered rules: claims staff log in with their own credentials; editing a claim needs a temporary authorization
-- from the claims manager; each change is logged under the staff member and the manager. The designated patient party
-- and the doctor can see entries and changes but cannot alter them. Audit is done quarterly.
-- The delivered system also audited edits to other tables, in a separate log; this sketch covers claims only.
-- Read-only access for patient party and doctor is enforced in the application (authorization schemes), not here.

CREATE TABLE edit_authorizations (
  auth_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  grantee_user  VARCHAR2(100) NOT NULL,      -- claims team member
  granted_by    VARCHAR2(100) NOT NULL,      -- claims manager
  valid_from    DATE DEFAULT SYSDATE NOT NULL,
  valid_until   DATE NOT NULL,               -- granted for 30 minutes: valid_until = valid_from + 30/1440
  revoked_at    DATE,                        -- set at logout, so the authorization ends at 30 minutes or logout, whichever is first
  reason        VARCHAR2(400),
  CONSTRAINT ck_no_self_grant CHECK (grantee_user <> granted_by)   -- a manager cannot authorize themselves
);

CREATE TABLE audit_log (
  audit_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  table_name     VARCHAR2(30) NOT NULL,
  row_id         NUMBER,
  action         VARCHAR2(10) NOT NULL,
  changed_by     VARCHAR2(100) NOT NULL,
  authorized_by  VARCHAR2(100),              -- the claims manager who granted the temporary authorization
  changed_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  old_values     CLOB,
  new_values     CLOB,
  important_flag CHAR(1) DEFAULT 'N' CHECK (important_flag IN ('Y','N')),   -- trails marked important survive the quarterly purge
  marked_by      VARCHAR2(10) CHECK (marked_by IN ('AUDITOR','SYSTEM'))      -- the auditors mark; the system flags what it judges important from their side
);
-- After each quarterly audit the Internal Audit team, with the system team, keep the trails marked important.
-- What happens to the unmarked trails (separate table, retention period, analysis) is their decision and sits outside the application.
-- Make the log append-only for the application schema (run as the schema owner / DBA):
--   REVOKE UPDATE, DELETE ON audit_log FROM <app_schema_role>;

CREATE OR REPLACE TRIGGER trg_claims_edit_audit
BEFORE UPDATE ON claims
FOR EACH ROW
DECLARE
  v_user VARCHAR2(100) := NVL(V('APP_USER'), USER);
  v_mgr  VARCHAR2(100);
BEGIN
  -- The insurer-integration account records decisions returned by the insurer's API. It needs no manager authorization,
  -- but every change it makes is still logged (authorized_by stays empty, changed_by shows the integration account).
  IF v_user = 'INSURER_INTEGRATION' THEN
    NULL;
  ELSE
  BEGIN
    SELECT granted_by INTO v_mgr
      FROM edit_authorizations
     WHERE grantee_user = v_user AND SYSDATE BETWEEN valid_from AND valid_until
       AND revoked_at IS NULL AND ROWNUM = 1;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20001, 'Editing a claim needs a current authorization from the claims manager');
  END;
  END IF;
  INSERT INTO audit_log (table_name, row_id, action, changed_by, authorized_by, old_values, new_values)
  VALUES ('CLAIMS', :OLD.claim_id, 'UPDATE', v_user, v_mgr,
          'claimed=' || :OLD.claimed_amount || ';approved=' || :OLD.approved_amount || ';status=' || :OLD.status || ';rule=' || :OLD.rule_code,
          'claimed=' || :NEW.claimed_amount || ';approved=' || :NEW.approved_amount || ';status=' || :NEW.status || ';rule=' || :NEW.rule_code);
END;
/
