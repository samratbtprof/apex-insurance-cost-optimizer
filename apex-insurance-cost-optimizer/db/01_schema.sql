-- apex-insurance-cost-optimizer : reference implementation (synthetic data only)
-- Target: Oracle Database 19c+ / Autonomous DB (APEX 23.x+)

CREATE TABLE providers (
  provider_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  provider_name   VARCHAR2(120) NOT NULL,
  provider_type   VARCHAR2(20)  CHECK (provider_type IN ('HOSPITAL','CLINIC','PHARMACY'))
);

CREATE TABLE insurance_plans (
  plan_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  plan_name           VARCHAR2(80) NOT NULL,
  annual_premium      NUMBER(12,2) NOT NULL,
  copay_pct           NUMBER(5,2)  DEFAULT 10,
  formulary_required  CHAR(1)      DEFAULT 'Y' CHECK (formulary_required IN ('Y','N'))
);

CREATE TABLE members (
  member_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  plan_id     NUMBER NOT NULL REFERENCES insurance_plans,
  age_band    VARCHAR2(10),
  city_tier   VARCHAR2(10)
);

CREATE TABLE drug_master (
  drug_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  drug_name        VARCHAR2(120) NOT NULL,
  generic_group    VARCHAR2(80)  NOT NULL,      -- same group = substitutable
  is_generic       CHAR(1)       CHECK (is_generic IN ('Y','N')),
  unit_cost        NUMBER(10,2)  NOT NULL,
  shelf_life_days  NUMBER(5)     NOT NULL,
  on_formulary     CHAR(1)       CHECK (on_formulary IN ('Y','N'))
);

CREATE TABLE reimbursement_rules (
  rule_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  rule_code      VARCHAR2(30) NOT NULL,
  version_no     NUMBER DEFAULT 1 NOT NULL,
  effective_from DATE DEFAULT DATE '2000-01-01' NOT NULL,   -- a claim is judged by the version in force on its date
  effective_to   DATE,
  description    VARCHAR2(400),
  rule_type      VARCHAR2(20) CHECK (rule_type IN ('REJECT','SHORT_PAY','FLAG')),
  param_value    NUMBER,
  active_yn      CHAR(1) DEFAULT 'Y',
  CONSTRAINT uq_rule_version UNIQUE (rule_code, version_no)
);

CREATE TABLE prescriptions (
  rx_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  member_id      NUMBER NOT NULL REFERENCES members,
  provider_id    NUMBER NOT NULL REFERENCES providers,
  drug_id        NUMBER NOT NULL REFERENCES drug_master,
  rx_date        DATE   NOT NULL,
  rx_qty         NUMBER(6) NOT NULL
);

CREATE TABLE dispense_records (
  dispense_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  rx_id            NUMBER NOT NULL REFERENCES prescriptions,
  drug_id          NUMBER NOT NULL REFERENCES drug_master,   -- may differ from rx (substitution)
  dispense_date    DATE   NOT NULL,
  dispensed_qty    NUMBER(6) NOT NULL,
  batch_expiry     DATE,
  unit_cost_paid   NUMBER(10,2) NOT NULL
);

CREATE TABLE claims (
  claim_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  dispense_id      NUMBER NOT NULL REFERENCES dispense_records,
  member_id        NUMBER NOT NULL REFERENCES members,
  claim_date       DATE   NOT NULL,
  claimed_amount   NUMBER(12,2) NOT NULL,
  approved_amount  NUMBER(12,2),
  status           VARCHAR2(12) CHECK (status IN ('APPROVED','SHORT_PAID','REJECTED')),
  rule_code        VARCHAR2(30),
  rule_version     NUMBER
);

CREATE TABLE stock_wastage (
  wastage_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  drug_id       NUMBER NOT NULL REFERENCES drug_master,
  provider_id   NUMBER NOT NULL REFERENCES providers,
  written_off   DATE   NOT NULL,
  qty           NUMBER(8) NOT NULL,
  reason        VARCHAR2(20) CHECK (reason IN ('EXPIRED','OVERSTOCK','DAMAGED'))
);

-- Leakage view: money lost or avoidably spent. One cause per claim, by priority:
--   1 OFF_FORMULARY, 2 OVER_DISPENSE, 3 GENERIC_MISSED, 4 REIMBURSEMENT_LOSS (any other rejection or short-pay).
-- Claims with no leakage are excluded, so SUM(leakage_amount) is safe to use on a dashboard.
CREATE OR REPLACE VIEW v_claim_leakage AS
SELECT claim_id, claim_month, leakage_type, leakage_amount
FROM (
  SELECT c.claim_id,
         TRUNC(c.claim_date,'MM') AS claim_month,
         CASE
           WHEN d_ds.on_formulary = 'N'                         THEN 'OFF_FORMULARY'
           WHEN ds.dispensed_qty > rx.rx_qty                    THEN 'OVER_DISPENSE'
           WHEN d_ds.is_generic = 'N' AND gen.min_cost IS NOT NULL THEN 'GENERIC_MISSED'
           WHEN c.status IN ('REJECTED','SHORT_PAID')           THEN 'REIMBURSEMENT_LOSS'
         END AS leakage_type,
         CASE
           WHEN d_ds.on_formulary = 'N'                         THEN c.claimed_amount - NVL(c.approved_amount,0)
           WHEN ds.dispensed_qty > rx.rx_qty                    THEN (ds.dispensed_qty - rx.rx_qty) * ds.unit_cost_paid
           WHEN d_ds.is_generic = 'N' AND gen.min_cost IS NOT NULL
                                                                THEN GREATEST(ds.unit_cost_paid - gen.min_cost, 0) * ds.dispensed_qty
           WHEN c.status IN ('REJECTED','SHORT_PAID')           THEN c.claimed_amount - NVL(c.approved_amount,0)
         END AS leakage_amount
  FROM claims c
  JOIN dispense_records ds ON ds.dispense_id = c.dispense_id
  JOIN prescriptions rx    ON rx.rx_id = ds.rx_id
  JOIN drug_master d_ds    ON d_ds.drug_id = ds.drug_id
  LEFT JOIN (SELECT generic_group, MIN(unit_cost) AS min_cost
               FROM drug_master WHERE is_generic = 'Y' GROUP BY generic_group) gen
         ON gen.generic_group = d_ds.generic_group
)
WHERE leakage_type IS NOT NULL;

-- Wastage view
CREATE OR REPLACE VIEW v_drug_wastage AS
SELECT TRUNC(w.written_off,'MM') AS wastage_month,
       dm.drug_name, w.reason, w.qty,
       w.qty * dm.unit_cost       AS wastage_value
FROM stock_wastage w JOIN drug_master dm ON dm.drug_id = w.drug_id;
