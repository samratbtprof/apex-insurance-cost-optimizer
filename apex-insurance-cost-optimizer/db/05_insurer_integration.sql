-- Insurer integration (reference sketch; NOT run on Oracle, test in your APEX workspace first)
-- Delivered design: a few insurers were integrated by API, each with its own rule set set up from that insurer's rules at
-- integration time. For insurers without an API, the documents were sent as a password-protected zip by email to the person
-- assigned at the insurer, and the claims team entered the insurer's feedback. Rejection codes were stored with plain-language
-- text when each insurer was integrated.

CREATE TABLE insurers (
  insurer_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  insurer_name      VARCHAR2(120) NOT NULL,
  integration_mode  VARCHAR2(10) NOT NULL CHECK (integration_mode IN ('API','MANUAL'))
);

ALTER TABLE insurance_plans ADD (insurer_id NUMBER REFERENCES insurers);

-- one rule set per integrated insurer
ALTER TABLE reimbursement_rules ADD (insurer_id NUMBER REFERENCES insurers);
ALTER TABLE reimbursement_rules DROP CONSTRAINT uq_rule_version;
ALTER TABLE reimbursement_rules ADD CONSTRAINT uq_insurer_rule_version UNIQUE (insurer_id, rule_code, version_no);

CREATE TABLE insurer_rejection_codes (
  insurer_id   NUMBER NOT NULL REFERENCES insurers,
  reject_code  VARCHAR2(40) NOT NULL,
  plain_text   VARCHAR2(400) NOT NULL,      -- shown to the claims team, doctor and patient party next to the code
  PRIMARY KEY (insurer_id, reject_code)
);

CREATE TABLE claim_submissions (
  submission_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  claim_id         NUMBER NOT NULL REFERENCES claims,
  insurer_id       NUMBER NOT NULL REFERENCES insurers,
  status           VARCHAR2(20) DEFAULT 'QUEUED' CHECK (status IN
                     ('QUEUED','SENDING','PENDING_AT_INSURER','DECIDED','SENT_BY_MAIL')),
  idempotency_key  VARCHAR2(80) NOT NULL,   -- sent with the API call, so a retry after a lost reply cannot create a second submission
  insurer_ref_tag  VARCHAR2(80),             -- tag returned by the insurer's API; once set, the submission is locked
  attempts         NUMBER(3) DEFAULT 0,      -- automated retries continue until the insurer's system is up
  submitted_at     DATE,
  decided_at       DATE,
  decision         VARCHAR2(10) CHECK (decision IN ('APPROVED','REJECTED')),
  reject_code      VARCHAR2(40),
  insurer_note     VARCHAR2(1000),           -- any note sent from the insurer's end
  CONSTRAINT uq_idempotency_key UNIQUE (idempotency_key),
  CONSTRAINT uq_one_submission_per_claim UNIQUE (claim_id)   -- the delivered app checked duplicates by patient id; see review notes
);

-- Order of work for an API submission: (1) save status = 'SENDING' with the idempotency key in this table,
-- (2) call the insurer's API, (3) store the returned tag and set 'PENDING_AT_INSURER'.
-- If the reply is lost, the row stays 'SENDING' and the retry reuses the same key.

-- What the claims team, doctor and patient party see
CREATE OR REPLACE VIEW v_claim_decision AS
SELECT cs.claim_id,
       CASE WHEN cs.status IN ('QUEUED','SENDING','PENDING_AT_INSURER','SENT_BY_MAIL')
            THEN 'Decision pending at insurer end' ELSE cs.decision END AS shown_status,
       cs.reject_code,
       rc.plain_text AS reject_reason,
       cs.insurer_note
FROM claim_submissions cs
LEFT JOIN insurer_rejection_codes rc
       ON rc.insurer_id = cs.insurer_id AND rc.reject_code = cs.reject_code;

